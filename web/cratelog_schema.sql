CREATE TABLE IF NOT EXISTS cratelog_albums (
 id CHAR(36) PRIMARY KEY,
 rating DECIMAL(2,1) UNSIGNED NOT NULL DEFAULT 0,
 personal_comment TEXT NULL,
 documents JSON NULL,
 local_path TEXT NOT NULL,
 metadata JSON NOT NULL,
 images JSON NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS cratelog_tracks (
 album_id CHAR(36) NOT NULL,
 position INT UNSIGNED NOT NULL,
 filename VARCHAR(512) NOT NULL,
 selected BOOLEAN NOT NULL DEFAULT FALSE,
 highlighted BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY (album_id, position),
 FOREIGN KEY (album_id) REFERENCES cratelog_albums(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
